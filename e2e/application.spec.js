import { test, expect } from '@playwright/test'

test('navegação pública carrega as telas sem erros de compilação ou execução', async ({ page }) => {
  const errors = []
  let movementRequests = 0
  page.on('request', request => { if (new URL(request.url()).pathname === '/api/movements') movementRequests++ })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  const screens = { dashboard: 'Consultar materiais', catalogo: 'Catálogo', inventario: 'Controle de estoque', movimentacoes: 'Histórico de movimentações', ordens: 'Ordens de Serviço', motores: 'Motores', relatorios: 'Relatórios' }
  for (const [tab, title] of Object.entries(screens)) {
    await page.goto(`/#/${tab}`)
    await expect(page.locator('main').getByRole('heading', { name: title, exact: true, level: tab === 'catalogo' ? 2 : 1 })).toBeVisible()
    await expect(page.locator('vite-error-overlay')).toHaveCount(0)
  }
  expect(errors).toEqual([])
  expect(movementRequests).toBe(1)
})


  await audit.getByLabel('Buscar na auditoria').fill('duplicado')
  await audit.getByRole('button', { name: 'Filtrar', exact: true }).click()
  await expect(audit.getByText('Lançamento duplicado na origem', { exact: true })).toBeVisible()

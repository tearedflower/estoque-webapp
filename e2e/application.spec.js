  await page.evaluate(() => window.dispatchEvent(new Event('app:data-invalidated')))
  await expect(page.locator('tbody').getByText('Atualização externa', { exact: true })).toHaveCount(1)
  await edit.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(edit).toBeVisible()

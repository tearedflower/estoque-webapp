  await edit.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await page.getByTitle('Editar movimentação').first().click()
  await edit.locator('input[type="number"]').first().fill('8')
  await edit.getByLabel('Motivo da correção').fill('Quantidade conferida no recebimento')
  await edit.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(edit).toHaveCount(0)
  await expect(page.getByTitle('Histórico de alterações')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Alterações e exclusões' })).toHaveCount(0)
  await page.getByRole('link', { name: 'Administração', exact: true }).click()
  await page.getByRole('button', { name: 'Auditoria', exact: true }).click()
  await expect(page).toHaveURL(/subTab=auditoria/)
  const audit = page.getByRole('region', { name: 'Auditoria de movimentações' })
  await expect(audit.getByRole('heading', { name: 'Auditoria', exact: true })).toBeVisible()
  const correction = audit.getByRole('row').filter({ hasText: 'Quantidade conferida no recebimento' })
  await correction.getByText('Ver detalhes', { exact: true }).click()
  await expect(correction.getByText('Quantidade', { exact: true }).locator('..').getByText('10 → 8', { exact: true })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('auditoria-desktop.png'), fullPage: true })
  const response = await page.request.get(`/api/movements/${entry.id}/audit`)
  expect(response.status()).toBe(200)
  await page.goto('/#/movimentacoes?subTab=historico')
  await page.getByTitle('Remover do histórico').first().click()
  const remove = page.getByRole('dialog', { name: 'Excluir movimentação?' })
  await remove.getByLabel('Motivo da exclusão').fill('Lançamento duplicado na origem')
  await remove.getByRole('button', { name: 'Excluir e registrar motivo' }).click()
  await expect(remove).not.toBeVisible()
  await page.goto('/#/cadastros?subTab=auditoria')
  await expect(audit.getByText('Lançamento duplicado na origem', { exact: true })).toBeVisible()
  await page.reload()
  await expect(audit.getByRole('heading', { name: 'Auditoria', exact: true })).toBeVisible()

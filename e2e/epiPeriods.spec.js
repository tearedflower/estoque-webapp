test('saída individual de EPI preenche quantidade com uma ou várias variações', async ({ page }) => {
  const errors = []
  page.on('pageerror', cause => errors.push(cause.message))
  let login = await page.request.post('/api/auth/login', { data: { login: 'admin', pin: 'senha-browser-123' } })
  if (login.status() === 401) login = await page.request.post('/api/auth/login', { data: { login: 'admin', pin: 'admin123' } })
  expect(login.status()).toBe(200)
  const { user } = await login.json()
  if (user.mustChangePassword) expect((await page.request.put(`/api/auth/users/${user.id}`, { data: { pin: 'senha-browser-123' } })).status()).toBe(200)
  const create = async (path, data) => {
    const response = await page.request.post(path, { data })
    expect(response.status()).toBe(200)
    return response.json()
  }
  await create('/api/roles', { name: 'Reposição Teste' })
  const person = await create('/api/people', { name: 'Pessoa reposição teste', role: 'Reposição Teste' })
  const destination = await create('/api/destinations', { name: 'EPI' })
  for (const quantity of [3, 4]) {
    const item = await create('/api/items', { name: `EPI reposição ${quantity}`, group: 'EPI', unit: 'PAR', attributes: ['Tamanho'] })
    let firstVariation
    for (let index = 0; index < quantity - 2; index++) {
      const variation = await create('/api/items/variations', { itemId: item.id, values: { Tamanho: String(40 + index) }, stock: 0 })
      firstVariation ??= variation
      await create('/api/movements', { type: 'entrada', itemId: item.id, variationId: variation.id, itemName: item.name, qty: 20, stockCounts: { [variation.id]: 0 } })
    }
    await create('/api/epis/role-rules', { roleName: person.role, targetType: 'item', targetKey: item.id, targetLabel: item.name, days: 90, quantity })
    await page.goto('/#/inventario?section=epis')
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Controle de EPIs' })).toBeVisible()
    const record = page.getByRole('row').filter({ hasText: item.name }).filter({ hasText: person.name })
    const actionsHeader = await page.getByRole('columnheader', { name: 'Ações', exact: true }).boundingBox()
    const firstAction = await record.getByRole('button', { name: 'Itens compatíveis', exact: true }).boundingBox()
    const lastAction = await record.getByRole('button', { name: /Selecionar reposição de/ }).boundingBox()
    expect(Math.abs(actionsHeader.x + actionsHeader.width / 2 - (firstAction.x + lastAction.x + lastAction.width) / 2)).toBeLessThan(1)
    if (quantity === 4) {
      const upToDate = page.getByRole('row').filter({ hasText: 'EPI reposição 3' }).filter({ hasText: person.name })
      await expect(upToDate.getByText('Em dia', { exact: true })).toBeVisible()
      await expect(upToDate.getByRole('button', { name: /Selecionar reposição de/ })).toBeEnabled()
      const pendingAction = await record.getByRole('button', { name: 'Registrar saida', exact: true }).boundingBox()
      const currentAction = await upToDate.getByRole('button', { name: 'Registrar saida', exact: true }).boundingBox()
      expect(Math.abs(pendingAction.x - currentAction.x)).toBeLessThan(1)
      await upToDate.getByRole('button', { name: /Selecionar reposição de/ }).click()
      await page.getByRole('button', { name: 'Registrar reposições (1)', exact: true }).click()
      const bulk = page.getByRole('dialog', { name: 'Registrar reposições de EPI' })
      await expect(bulk.getByText('Em dia', { exact: true })).toBeVisible()
      await bulk.getByRole('button', { name: 'Confirmar entregas', exact: true }).click()
      await expect(bulk).not.toBeVisible()
      const movements = await (await page.request.get('/api/movements')).json()
      expect(movements.filter(row => row.requestedByPersonId === person.id && row.itemName === 'EPI reposição 3' && row.qty === 3)).toHaveLength(1)
    }
    await record.getByRole('button', { name: `Selecionar reposição de ${item.name} para ${person.name}` }).click()
    await expect(record.getByRole('button', { name: `Desmarcar reposição de ${item.name} para ${person.name}` })).toHaveAttribute('aria-pressed', 'true')
    await record.getByRole('button', { name: `Desmarcar reposição de ${item.name} para ${person.name}` }).click()
    await record.getByRole('button', { name: 'Itens compatíveis', exact: true }).click()
    const compatiblePopup = page.getByRole('dialog', { name: 'Itens compatíveis com o EPI' })
    await expect(compatiblePopup.locator('article')).toHaveCount(quantity - 2)
    await expect(compatiblePopup.getByRole('heading', { name: item.name, exact: true })).toHaveCount(quantity - 2)
    await expect(compatiblePopup.getByText('20 PAR', { exact: true })).toHaveCount(quantity - 2)
    if (quantity === 4) await expect(compatiblePopup.getByRole('heading', { name: 'EPI reposição 3', exact: true })).toHaveCount(0)
    await compatiblePopup.getByRole('button', { name: 'Fechar itens compatíveis' }).click()
    await expect(compatiblePopup).not.toBeVisible()
    await record.getByRole('button', { name: 'Registrar saida', exact: true }).click()
    if (quantity === 4) await page.getByRole('row').filter({ has: page.getByRole('cell', { name: '40', exact: true }) }).click()
    await expect(page.locator('main input[type="number"]').first()).toHaveValue(String(quantity))
    if (quantity === 3) await create('/api/movements', { type: 'saida', itemId: item.id, variationId: firstVariation.id, itemName: item.name, qty: 1, requestedByPersonId: person.id, destinationId: destination.id })
  }
  expect(errors).toEqual([])
})
